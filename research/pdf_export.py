"""Convert a CompanyIQ Markdown report into a PDF."""

from datetime import date
from pathlib import Path

import markdown
from fpdf import FPDF
from fpdf.fonts import TextStyle

FONT_DIR = Path(__file__).resolve().parent.parent / "fonts"
FONT_FAMILY = "DejaVu"
HEADING_COLOR = (31, 56, 100)

TAG_STYLES = {
    "h1": TextStyle(font_family=FONT_FAMILY, font_style="B", font_size_pt=17,
                    color=HEADING_COLOR, t_margin=4, b_margin=0.4),
    "h2": TextStyle(font_family=FONT_FAMILY, font_style="B", font_size_pt=14,
                    color=HEADING_COLOR, t_margin=3, b_margin=0.3),
    "h3": TextStyle(font_family=FONT_FAMILY, font_style="B", font_size_pt=12,
                    color=HEADING_COLOR, t_margin=4, b_margin=0.4),
    "h4": TextStyle(font_family=FONT_FAMILY, font_style="B", font_size_pt=11,
                    color=HEADING_COLOR, t_margin=3, b_margin=0.3),
}


def _strip_unsupported(text: str) -> str:
    """Drop characters the bundled font can't draw (mostly emoji)."""

    return "".join(ch for ch in text if ord(ch) <= 0xFFFF)


def _register_fonts(pdf: FPDF) -> None:
    regular = FONT_DIR / "DejaVuSans.ttf"
    bold = FONT_DIR / "DejaVuSans-Bold.ttf"

    pdf.add_font(FONT_FAMILY, "", regular)
    pdf.add_font(FONT_FAMILY, "B", bold)
    # The bundled font has no italic files, so italics fall back to upright.
    pdf.add_font(FONT_FAMILY, "I", regular)
    pdf.add_font(FONT_FAMILY, "BI", bold)


def report_to_pdf(company_name: str, report_markdown: str) -> bytes:
    """Render the Markdown report as a PDF and return its bytes."""

    pdf = FPDF(format="A4")
    pdf.set_margins(18, 18, 18)
    pdf.set_auto_page_break(auto=True, margin=18)
    _register_fonts(pdf)

    pdf.set_title(f"CompanyIQ Research: {company_name}")
    pdf.set_creator("CompanyIQ")
    pdf.add_page()

    pdf.set_font(FONT_FAMILY, "B", 20)
    pdf.set_text_color(*HEADING_COLOR)
    pdf.multi_cell(
        0, 10,
        _strip_unsupported(f"Company Research: {company_name}"),
        new_x="LMARGIN", new_y="NEXT",
    )
    pdf.set_font(FONT_FAMILY, "", 9)
    pdf.set_text_color(110, 110, 110)
    pdf.cell(
        0, 6, f"Generated by CompanyIQ on {date.today():%B %d, %Y}",
        new_x="LMARGIN", new_y="NEXT",
    )
    pdf.ln(6)
    pdf.set_text_color(0, 0, 0)

    html = markdown.markdown(
        _strip_unsupported(report_markdown),
        extensions=["tables", "sane_lists"],
    )

    pdf.set_font(FONT_FAMILY, "", 11)
    pdf.write_html(html, font_family=FONT_FAMILY, tag_styles=TAG_STYLES,
                   li_prefix_color=HEADING_COLOR)

    return bytes(pdf.output())
